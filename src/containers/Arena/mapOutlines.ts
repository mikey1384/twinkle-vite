// Simplified outlines for Arena's code-drawn maps (10-25), written by hand
// as [lon, lat] pairs: coasts to roughly 50-150 km, borders as their main
// turns. Good for a 통합사회/한국사 locator map where the text identifies
// the place; not survey-grade. Land polygons run past the default bounds
// and are clipped to the frame. twinkle-api helpers/arena/diagram.ts lists
// the same base, area and river names; keep the two in step.

export type LonLat = [number, number];

export interface MapBase {
  bounds: { west: number; east: number; south: number; north: number };
  // land masses (closed), drawn white with a black coast
  land: LonLat[][];
  // lakes (closed), drawn as water inside the land
  lakes: LonLat[][];
  // named areas (closed): a border drawn thin and dashed, shaded on request
  areas: Record<string, LonLat[]>;
  // other borders (open, thin dashed)
  borders: LonLat[][];
  // named rivers (open), drawn on request
  rivers: Record<string, LonLat[]>;
}

