// Every word the lite host shows, one dictionary per language, chosen by the
// browser (Mikey 11-25: the lite host is localized; Twinkle's own sign-up and
// sign-in screens on twin-kle.com stay English, parent pages Korean). The
// Korean should read as written in Korean, not translated.
export type LiteHostLang = 'en' | 'ko';

export function liteHostLang(): LiteHostLang {
  const languages =
    typeof navigator === 'undefined'
      ? []
      : navigator.languages?.length
        ? navigator.languages
        : [navigator.language];
  return languages.some((value) => /^ko\b/i.test(String(value || ''))) ? 'ko' : 'en';
}

